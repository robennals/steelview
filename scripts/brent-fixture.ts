/**
 * Writes the Storybook fixture `components/report/stories/fixtures/brent-daily.ts`
 * from EIA's daily Brent spot price page.
 *
 *   curl -o RBRTEd.htm https://www.eia.gov/dnav/pet/hist/RBRTEd.htm
 *   npx tsx scripts/brent-fixture.ts RBRTEd.htm > components/report/stories/fixtures/brent-daily.ts
 *
 * The page is EIA's HTML view of the same series as its `RBRTEd.xls`
 * download: one row per week, labelled "1987 May-18 to May-22", with a cell
 * for each weekday (empty when no price was reported). Reading the HTML
 * needs no spreadsheet parser. Run once; the fixture is committed.
 */
import { readFileSync } from 'node:fs';

const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

export function parseWeeklyRows(html: string): Array<[string, number]> {
  const points: Array<[string, number]> = [];
  const row = /<td class='B6'>(?:&nbsp;)*(\d{4}) ([A-Z][a-z]{2})- ?(\d{1,2}) to [A-Z][a-z]{2}- ?\d{1,2}<\/td>((?:\s*<td class='B3'>[^<]*<\/td>){5})/g;
  for (const match of html.matchAll(row)) {
    const [, year, month, day, cells] = match;
    const monday = Date.UTC(Number(year), MONTHS.indexOf(month), Number(day));
    const values = [...cells.matchAll(/<td class='B3'>([^<]*)<\/td>/g)].map(cell => cell[1].trim());
    values.forEach((value, weekday) => {
      if (value === '') return;
      const date = new Date(monday + weekday * 86_400_000).toISOString().slice(0, 10);
      points.push([date, Number(value)]);
    });
  }
  return points;
}

function main(): void {
  const file = process.argv[2];
  if (!file) throw new Error('usage: tsx scripts/brent-fixture.ts <RBRTEd.htm>');
  const html = readFileSync(file, 'utf8');
  const release = html.match(/Release Date: (\d+)\/(\d+)\/(\d{4})/);
  const points = parseWeeklyRows(html);
  if (points.length === 0 || !release) throw new Error('no weekly rows or release date found — has the page layout changed?');
  const released = `${release[3]}-${release[1].padStart(2, '0')}-${release[2].padStart(2, '0')}`;
  const [first] = points[0];
  const [last] = points[points.length - 1];

  process.stdout.write(`/**
 * Generated by scripts/brent-fixture.ts from EIA's daily Europe Brent spot
 * price (series RBRTE), released ${released}: all ${points.length.toLocaleString('en-GB')} daily values,
 * ${first} to ${last}, in dollars a barrel. Do not edit by hand.
 */
export const BRENT_RELEASED = '${released}';

export const BRENT_DAILY: Array<[string, number]> = [
${points.map(([date, value]) => `  ['${date}', ${value}],`).join('\n')}
];
`);
}

if (process.argv[1]?.endsWith('brent-fixture.ts')) main();
